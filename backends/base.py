"""The single backend protocol. No backend-specific code outside backends/."""
from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol


@dataclass
class Instance:
    idx: int
    name: str
    console_port: int
    adb_port: int
    proxy_port: int

    @property
    def serial(self) -> str:
        return f"emulator-{self.console_port}"


class EmulatorBackend(Protocol):
    def list_instances(self) -> list[Instance]: ...
    def create(self, name: str, device: str = "pixel_7") -> None: ...
    def clone(self, src: int, dst: int) -> None: ...
    def start(self, idx: int, headless: bool = True) -> None: ...
    def stop(self, idx: int) -> None: ...
    def stop_all(self) -> None: ...
    def is_booted(self, idx: int) -> bool: ...
    def adb_serial(self, idx: int) -> str: ...
    def set_proxy(self, idx: int, host_port: str | None) -> None: ...
    def randomize_identity(self, idx: int) -> None: ...
    def snapshot(self, idx: int, name: str) -> None: ...
    def restore(self, idx: int, name: str) -> None: ...
    def window(self, idx: int) -> None: ...